import assert from 'node:assert/strict';
import fs from 'node:fs';

const blog=fs.readFileSync('app/blog/blog-2026-09-10.ts','utf8');
const research=fs.readFileSync('app/research/research-2026-09-10.ts','utf8');
const prior=fs.readFileSync('app/blog/blog-2026-09-09.ts','utf8')+fs.readFileSync('app/research/research-2026-09-09.ts','utf8');
const september8=fs.readFileSync('app/blog/blog-2026-09-08.ts','utf8')+fs.readFileSync('app/research/research-2026-09-08.ts','utf8');
const get=(text,key)=>[...text.matchAll(new RegExp(`${key}:'([^']+)'`,'g'))].map(m=>m[1]);
const blogs=get(blog,'slug');
const studies=get(research,'slug');
const titles=[...get(blog,'title'),...get(research,'title')];
assert.equal(blogs.length,12);
assert.equal(studies.length,5);
assert.equal(new Set([...blogs,...studies]).size,17);
assert.equal(new Set(titles).size,17);
for(const value of [...blogs,...studies,...titles]) assert.ok(!prior.includes(value),`September 9 identity reused: ${value}`);
for(const value of [...blogs,...studies,...titles]) assert.ok(!september8.includes(value),`September 8 identity reused: ${value}`);
assert.ok(blog.includes("published:'2026-09-10'"));
assert.ok(research.includes("published:'2026-09-10'"));
assert.ok(blog.includes('Published September 10, 2026'));
assert.ok(research.includes('Published September 10, 2026'));
assert.doesNotMatch(blog+research,/—|–| -- /);
for(const heading of ['Methodology','Inference boundaries','Limitations','Sources']) assert.ok(heading==='Sources'||research.includes(`heading:'${heading}'`));
const data=fs.readFileSync('app/data.ts','utf8');
const fleet=fs.readFileSync('app/fleet-data.ts','utf8');
assert.ok(data.includes('...september10BlogPosts'));
assert.ok(fleet.includes('...september10ResearchPosts'));
for(const image of get(blog,'image')) assert.ok(fs.existsSync(`public${image}`),`missing image ${image}`);
assert.ok(fs.existsSync('public/research-thumbnails/research-default.svg'));
console.log(JSON.stringify({blogs,studies},null,2));
console.log('September 10 release: PASS');
