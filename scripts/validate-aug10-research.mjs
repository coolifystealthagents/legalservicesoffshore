import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';

const manifest = JSON.parse(fs.readFileSync('.paperclip/aug10-2026/research.json', 'utf8'));
const data = fs.readFileSync('app/fleet-data.ts', 'utf8');
const article = fs.readFileSync('app/research/[slug]/page.tsx', 'utf8');
const index = fs.readFileSync('app/research/page.tsx', 'utf8');
const sitemap = fs.readFileSync('app/sitemap.xml/route.ts', 'utf8');
assert.equal(manifest.schemaVersion, 1);
assert.equal(manifest.contract, 'sites3-aug10-public-date-v6');
assert.deepEqual(Object.keys(manifest), ['schemaVersion', 'contract', 'targetDate', 'family', 'domain', 'repository', 'branch', 'minimum', 'priorRunId', 'priorIssueId', 'validationCommands', 'cleanBuildPassed', 'existingCompliancePassed', 'indexNewestFirstPassed', 'entries']);
assert.equal(manifest.targetDate, '2026-08-10');
assert.equal(manifest.domain, 'legalservicesoffshore.com');
assert.equal(manifest.repository, 'coolifystealthagents/legalservicesoffshore');
assert.equal(manifest.branch, 'main');
assert.equal(manifest.minimum, 10);
assert.equal(manifest.priorRunId, 'e66f55c7-87b9-4167-adb2-b552b708e03f');
assert.equal(manifest.priorIssueId, '36ab9594-f1c0-4734-8ae6-4db24a0ad0c0');
assert.equal(manifest.cleanBuildPassed, true);
assert.equal(manifest.existingCompliancePassed, true);
assert.equal(manifest.indexNewestFirstPassed, true);
assert.equal(manifest.family, 'research');
assert.equal(manifest.entries.length, 15);
assert.equal(new Set(manifest.entries.map((e) => e.slug)).size, manifest.entries.length);
const frozenBatch = ['law-firm-document-intake-indexing', 'law-firm-intake-source-verification', 'law-firm-secure-file-transfer-checklist', 'legal-access-deprovisioning-workflow', 'legal-citation-library-maintenance', 'legal-client-follow-up-queue-controls', 'legal-data-retention-exception-queue', 'legal-deadline-escalation-matrix', 'legal-document-version-control', 'legal-entity-records-change-log', 'legal-form-completion-quality-controls', 'legal-matter-status-reporting', 'legal-privilege-review-administration', 'legal-qa-sampling-plan', 'legal-work-product-handoff-checklist'];
assert.deepEqual(new Set(manifest.entries.map((e) => e.slug)), new Set(frozenBatch));
for (const e of manifest.entries) {
  assert.deepEqual(Object.keys(e), ['slug', 'route', 'sourcePath', 'provenance', 'introducedByCommit', 'sourceDateField', 'sourceDate', 'renderedDateFields', 'renderedDate']);
  assert.match(e.route, /^\/research\/[a-z0-9-]+$/);
  assert.equal(e.route, `/research/${e.slug}`);
  assert.equal(e.sourcePath, 'app/fleet-data.ts');
  assert.equal(e.provenance, 'original-aug10-batch');
  assert.equal(e.sourceDateField, 'sourceDate');
  assert.equal(e.sourceDate, '2026-08-10');
  assert.equal(e.renderedDate, '2026-08-10');
  assert.ok(e.renderedDateFields.includes('datePublished'));
  assert.ok(e.renderedDateFields.includes('article:published_time'));
  assert.ok(e.renderedDateFields.includes('time[datetime]'));
  assert.equal(e.introducedByCommit, '67654aa2b09e712ce40968cab0e5d5b888b2c01e');
  const original = execFileSync('git', ['show', `${e.introducedByCommit}:app/fleet-data.ts`], { encoding: 'utf8' });
  assert.match(original, new RegExp(`makeResearch\\('${e.slug}'`));
  assert.match(data, new RegExp(`'${e.slug}': '2026-08-10'`));
  assert.match(article, /datePublished/);
  assert.match(article, /article:published_time/);
  assert.match(article, /time dateTime/);
  assert.match(article, /alternates:\{canonical/);
  assert.match(sitemap, /researchPosts\.map/);
}
assert.match(index, /sortedResearchPosts/);
assert.match(index, /b\.published\.localeCompare\(a\.published\)/);
console.log(`August 10 Research manifest regression: PASS (${manifest.entries.length} entries)`);
